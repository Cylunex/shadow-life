test("store menu reuses legacy foods, serializes concurrent enrolment and never turns menu images into meals",pgOnly,async t=>{
  const {run,queries,context,pool}=await reviewFixture(t),merchant="合成东食堂",dish="炒青菜";
  const old=await run("life.save_food",{name:merchant+"｜"+dish,provenance:"历史餐次与摄入出处",serving_amount:"80",serving_unit:"g",nutrients:{fiber_g:"1"}});
  assert.equal((await queries.merchantMenu(context,{merchant})).items[0]?.id,old.actual_values.food_id);
  await run("life.save_food",{name:"普通名称｜规格"});
  assert.equal((await queries.merchantMenu(context,{merchant:"普通名称"})).items.length,0);
  assert.equal((await pool.query("select count(*)::int n from merchant_foods")).rows[0].n,0);
  const input={merchant,dish,evidence:{kind:"note",note:"明示菜名"}};
  const writes=await Promise.all([run("life.remember_merchant_dish",input),run("life.remember_merchant_dish",input)]);
  assert.ok(writes.every(r=>r.actual_values.food_id===old.actual_values.food_id));
  const food=String(old.actual_values.food_id);
  const meal=await run("life.record_meal",{occurred_on:"2026-11-13",time_zone:"Asia/Shanghai",meal_type:"lunch",
    items:[{name:dish,food_ref_id:food,amount_g:"52",estimate:true,evidence_note:"当餐估重"}]});
  const meal_id=String(meal.actual_values.meal_id);
  const item=(await pool.query("select id,food_ref_id from intake_items where meal_id=$1",[meal_id])).rows[0];assert.equal(item.food_ref_id,food);
  await run("life.remember_merchant_dish",{merchant,dish,evidence:{kind:"meal_intake",meal_id,intake_id:item.id}});
  const other=await run("life.remember_merchant_dish",{...input,merchant:"合成西食堂"});assert.notEqual(other.actual_values.food_id,food);
  const pic=await new AssetService(pool).store(context.subjectId,"image/png",Buffer.from("synthetic menu"));
  const library=await run("library.capture",{title:"合成菜单",item_type:"image",tags:[],source:{kind:"image",captured_on:"2026-11-13",asset_version_id:pic.asset_version_id}});
  await run("life.remember_merchant_dish",{merchant,dish:"凉菜",evidence:{kind:"menu_photo",library_item_id:library.actual_values.library_item_id}});
  const pref={key:"dining.usual_canteen",scope:"daily",kind:"preference",category:"dietary",assertion:"explicit",statement:"常去食堂："+merchant};
  const selected=await run("agent.set_intention",pref);
  const first=await queries.merchantMenu(context,{limit:1});assert.equal(first.merchant,merchant);assert.ok(first.next);
  const second=await queries.merchantMenu(context,{after:first.next,limit:1});assert.notEqual(second.items[0]?.id,first.items[0]?.id);
  await run("agent.set_intention",{...pref,id:selected.actual_values.id,expected_revision:1,statement:"常去食堂：合成西食堂",reason:"更换门店"});
  assert.equal((await queries.merchantMenu(context,{})).items[0]?.id,other.actual_values.food_id);
  const prior=(await queries.merchantMenu(context,{merchant,query:dish})).items[0]!;
  assert.equal(prior.id,food);assert.equal(prior.provenance,"历史餐次与摄入出处");assert.equal(Number(prior.serving_amount),80);
  assert.equal(prior.evidence.find(r=>r.kind==="meal_intake")?.intake_id,item.id);
  assert.equal((await pool.query("select count(*)::int n from meals")).rows[0].n,1);
});

test("stall price periods and net weight evidence remain independent of receipt counts",pgOnly,async t=>{
  const f=await reviewFixture(t),merchant="合成食堂",dish="青菜";
  const base={merchant,dish,evidence:{kind:"note",note:"合成价目原件"}};
  const price={stall:"自选菜",price_name:"称重菜",valid_from:"2026-10-01",terms:{mode:"by_weight",price_cny:"2.00",per_grams:"100",staple_fee_cny:"1.00"},evidence_note:"菜单第一行"};
  const first=await f.run("life.remember_merchant_dish",{...base,stall_price:price});
  const updated=await f.run("life.remember_merchant_dish",{...base,stall_price:{...price,valid_from:"2026-11-01",terms:{...price.terms,price_cny:"3.00"}}});
  assert.equal(first.actual_values.food_id,updated.actual_values.food_id);
  const old=await f.queries.merchantMenu(f.context,{merchant,on:"2026-10-31"});
  assert.equal(old.stall_prices?.[0]?.valid_to_exclusive,"2026-11-01");
  assert.equal(old.stall_prices?.[0]?.terms.price_cny,"2.00");
  const item={name:dish,amount_g:"100",weight_basis:"payment_derived",estimate:true,evidence_note:"(3-1)/2×100"};
  const meal={occurred_on:"2026-10-31",time_zone:"UTC",meal_type:"breakfast",items:[item]};
  await assert.rejects(()=>f.run("life.record_meal",{...meal,items:[{...item,estimate:false}]}));
  const receipt=await f.run("life.record_meal",meal);
  const detail=await f.queries.lifeRecord(f.context,String(receipt.actual_values.meal_id));
  assert.ok(detail.kind==="meal");assert.equal(detail.items?.[0]?.weight_basis,"payment_derived");
  const asset=await new AssetService(f.pool).store(f.context.subjectId,"image/png",Buffer.from("synthetic"));
  for(let i=0;i<5;i++)await f.run("life.capture_screenshot",{asset_version_id:asset.asset_version_id,title:"合成凭据"+i,captured_at:"2026-10-31T12:00:00Z",time_zone:"UTC",recognition:"save"});
  const day={date:"2026-10-31",time_zone:"UTC"},workspace=await f.queries.captureWorkspace(f.context,day);
  assert.equal(workspace.image_materials?.length,5);assert.deepEqual(workspace.recorded_meals,[{meal_id:receipt.actual_values.meal_id,meal_type:"breakfast"}]);
  const limited=await f.queries.captureWorkspace({...f.context,effects:new Set(["library.item.read"])},day);
  assert.equal(limited.recorded_meals,undefined);
});

test("dining directory reads order dishes separately from distinct eaten meals",pgOnly,async t=>{
  const {run,queries,context}=await reviewFixture(t);
  const on={occurred_on:"2026-11-18",time_zone:"Asia/Shanghai"};
  const merchant="合成面馆",dish="鸡腿盖饭";
  const food=await run("life.remember_merchant_dish",{merchant,dish,evidence:{kind:"note",note:"核对菜单"}});
  const item={name:dish,food_ref_id:food.actual_values.food_id};
  const first=await run("life.record_meal",{...on,meal_type:"lunch",items:[item,item,{name:"没有吃的面",consumed_fraction:"0"}]});
  await run("life.record_meal",{...on,occurred_on:"2026-11-19",meal_type:"lunch",items:[item]});
  await run("life.record_meal",{...on,occurred_on:"2026-10-01",meal_type:"lunch",items:[item]});
  const order=await run("life.record_purchase",{...on,scene:"delivery",merchant_name_raw:merchant,
    items:[{raw_name:dish},{raw_name:"包装费"},{raw_name:"不要餐具"}]});
  await run("life.link_meal_consumption",{meal_id:first.actual_values.meal_id,consumption_record_id:order.actual_values.record_id,evidence:"user_confirmed"});
  const orderOnly=await run("life.record_purchase",{...on,scene:"delivery",merchant_name_raw:"只点过的店",items:[{raw_name:"牛肉米线"}]});
  await run("life.record_purchase",{...on,scene:"delivery",merchant_name_raw:"生鲜超市",items:[{raw_name:"苹果"}]});

  const readOnly={...context,effects:new Set(["life.meal.read"])};
  const result=await queries.merchantMenu(readOnly,{browse:"1",on:"2026-11-19",time_zone:"Asia/Shanghai"});
  assert.equal(result.merchant,"");
  const directory=result.directory!;
  assert.deepEqual(directory.merchants,[{name:merchant,menu_items:1,meals:2}]);
  assert.equal(directory.dishes.length,1);
  assert.equal(directory.dishes[0]?.meals,2);
  assert.equal(directory.dishes[0]?.food_id,food.actual_values.food_id);
  assert.deepEqual(directory.takeout.find(row=>row.record_id===order.actual_values.record_id)?.items,[dish]);
  assert.equal(directory.takeout.find(row=>row.record_id===order.actual_values.record_id)?.linked_meal,true);
  assert.equal(directory.takeout.find(row=>row.record_id===orderOnly.actual_values.record_id)?.linked_meal,false);
  assert.equal(directory.takeout.some(row=>row.merchant==="生鲜超市"),false);
  const store=await queries.merchantMenu(readOnly,{browse:"1",merchant,on:"2026-11-19"});
  assert.equal(store.items[0]?.id,food.actual_values.food_id);
  assert.equal(store.directory?.takeout.length,1);
  await assert.rejects(()=>queries.merchantMenu({...readOnly,effects:new Set()},{browse:"1"}),/permission/i);
});

test("dish statistics page counts distinct meals, including single visits and menu backfill evidence",pgOnly,async t=>{
  const {run,queries,context,pool}=await reviewFixture(t);
  const east="合成东店",west="合成西店",menuOnly="仅有菜单的门店";
  const on="2026-11-19",date={occurred_on:on,time_zone:"Asia/Shanghai",meal_type:"lunch"};
  const readOnly={...context,effects:new Set(["life.meal.read"])};
  const stats=async (filters:Record<string,unknown>={})=>(await queries.merchantMenu(readOnly,{stats:"1",on,...filters})).statistics!;
  const remember=(merchant:string,dish:string,stall?:string)=>run("life.remember_merchant_dish",{merchant,dish,stall,evidence:{kind:"note",note:"合成菜单"}});
  const original=await run("life.record_meal",{...date,occurred_on:"2026-10-21",items:[{name:"小份豆腐"},{name:"米饭"}]});
  const meal_id=original.actual_values.meal_id;
  const intake_id=(await pool.query("select id from intake_items where meal_id=$1 and position=0",[meal_id])).rows[0].id;
  const tofu=await run("life.remember_merchant_dish",{merchant:east,dish:"烧豆腐",stall:"素食",evidence:{kind:"meal_intake",meal_id,intake_id}});
  const tofuId=tofu.actual_values.food_id;
  const item={name:"烧豆腐",food_ref_id:tofuId};
  const current=await run("life.record_meal",{...date,items:[item,item,{name:"烧豆腐"},{name:"米饭"},{name:"仅拍照",consumed_fraction:"0"}]});
  const westTofu=await remember(west,"烧豆腐","热菜");
  await run("life.record_meal",{...date,items:[{name:"烧豆腐",food_ref_id:westTofu.actual_values.food_id}]});
  await run("life.record_meal",{...date,occurred_on:"2026-10-20",items:[item]});
  await run("life.record_meal",{...date,occurred_on:"2026-11-20",items:[item]});
  await remember(menuOnly,"仅看了菜单的面");
  await run("life.record_purchase",{occurred_on:on,time_zone:"Asia/Shanghai",scene:"delivery",merchant_name_raw:menuOnly,items:[{raw_name:"外卖炒面"}]});
  const single=await run("life.record_meal",{...date,items:[{name:"家中苹果"}]});
  const all=await stats();
  assert.deepEqual([all.from,all.to,all.merchant,all.meals,all.dishes,all.next_offset],["2026-10-21",on,null,4,4,null]);
  const first=await stats({merchant:east,query:"豆腐",limit:1});
  assert.deepEqual([first.meals,first.dishes,first.items], [2,1,[{name:"烧豆腐",merchant:east,stall:"素食",food_id:tofuId,
    meals:2,last_eaten_on:on,meal_id:current.actual_values.meal_id}]]);
  const eastPage=await stats({merchant:east,limit:1}),next=await stats({merchant:east,limit:1,stats_offset:eastPage.next_offset});
  assert.deepEqual([eastPage.dishes,eastPage.meals,eastPage.next_offset,next.next_offset],[2,2,1,null]);
  assert.deepEqual([eastPage.items[0]!.name,next.items[0]!.name].sort(),["烧豆腐","米饭"].sort());
  assert.equal(all.items.find(d=>d.meal_id===single.actual_values.meal_id)?.merchant,null);
  const empty=await queries.merchantMenu(readOnly,{merchant:menuOnly,stats:"1",browse:"1",on});
  assert.equal(empty.directory?.merchants.find(m=>m.name===menuOnly)?.menu_items,1);
  assert.deepEqual([empty.statistics?.dishes,empty.statistics?.meals,empty.statistics?.items],[0,0,[]]);
  const isolated=await queries.merchantMenu({...readOnly,subjectId:"subject_another_owner"},{stats:"1",on});
  assert.equal(isolated.statistics?.meals,0);
  await run("life.correct_intake",{item_id:intake_id,expected_revision:1,consumed_fraction:"0.5",reason:"改份量"});
  assert.equal((await stats({merchant:east,query:"烧豆腐"})).meals,2);
  await run("life.correct_intake",{item_id:intake_id,expected_revision:2,item:{name:"炒洋葱"},reason:"更正菜名"});
  assert.equal((await stats({merchant:east,query:"烧豆腐"})).meals,1);
  assert.equal((await stats({query:"炒洋葱"})).items[0]?.meal_id,meal_id);
  await assert.rejects(()=>queries.merchantMenu({...readOnly,effects:new Set()},{stats:"1"}),/permission/i);
});
